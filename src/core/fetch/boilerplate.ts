/**
 * 「抽出来的这段到底是不是正文」—— 导航位 / 推荐位识别。
 *
 * ── 它解决什么问题 ──
 *
 * Readability 的失败有两种形态，而这套系统原先只防住了第一种：
 *
 *   1. **抽不到** —— 正文短于阈值，`Extraction.thin = true`，降级去试无头浏览器
 *   2. **抽错了** —— 页面主体确实是「一大块文本」，但那一块是导航/推荐位，
 *      不是文章。`thin` 判不出来（字数够多），`looksLikeCode` 也判不出来
 *      （它不是代码）。于是它带着 `error: undefined` 混进语料，看起来
 *      和一篇正常资料一模一样。
 *
 * 实测到的确凿样本（`data/sessions/Ascj_hG6B6`）：
 *
 *   URL:  https://www.bilibili.com/list/3537113337301588?oid=…&bvid=BV1r8nMz4EAj
 *   正文: 李宏毅 | 大模型（LLM）系列课程入门全集… 7413播放
 *         李宏毅 | Harness Engineer教程… 8117播放
 *
 * 一千多字的「正文」里没有一句是这个页面的内容，全是侧栏的「接下来播放」。
 * 它比抓不到更糟：抓不到会退化成摘要并被标注，而它会被当成一篇完整资料，
 * 并且因为字数多，在启发式图上拿到不低的权重。
 *
 * ── 判据是**量出来的** ──
 *
 * 拿全部 ≥300 字的去重文档（59 篇）分两组测：
 *
 *   | 信号 | 可疑 B 站页面（list/cheese/space） | 已知真正文 |
 *   |---|---|---|
 *   | 「N播放」出现次数 | 1、3、7、15、15、15、19、19、20、22、23 | **全部 0** |
 *   | B 站骨架词 | 命中 | 全部未命中 |
 *
 * 两组之间没有任何重叠，所以判据可以定得很干净。
 *
 * **顺带否掉一个想当然的假设**：一开始想用「短行占比」—— 推荐列表每一行都短。
 * 实测发现 runoob 0.68、CSDN 0.70 的**正常文章**这个值同样很高（正文里的标题、
 * 列表项、代码行本来就短）。这个信号因此作废。先量再写，就是为了避免把
 * 这种误判固化进代码。
 */

/**
 * 「N播放」这类计数标记。
 *
 * 它是视频站推荐位的指纹：正常文章里没人会这么说，而推荐列表里每条都带一个。
 */
const PLAY_MARK = /[\d.]+\s*[万亿千]?\s*播放/g;

/**
 * 出现几次就判为推荐列表。
 *
 * 实测最小值是 1（一篇 810 字的 `/list/` 页），最大值 23。取 3 而不是 1：
 * 一篇**真的在讨论视频数据**的文章里，偶尔出现一两次「1000万播放」是合理的，
 * 那是正文的一部分；但连着一二十条就只可能是列表。取 3 既盖住了绝大部分
 * 样本，又给正常文章留了余量 —— 漏掉的那一条（只有 1 次）由下面的骨架词兜住。
 */
const PLAY_MARK_MIN = 3;

/**
 * B 站页面骨架。
 *
 * 这些字符串只在**页面框架**里出现，不在任何一篇文章的正文里：
 * `首页 番剧 直播` 是顶部导航条，`收藏 稿件 投诉` 是播放页的工具条。
 * 两个都是「多个相邻的界面词」，不是碰巧同现的实词。
 */
const BILIBILI_CHROME = [
  /首页\s*番剧\s*直播/,
  /收藏\s*稿件\s*投诉/,
];

/**
 * 判断一段提取出来的文本是不是导航/推荐位。
 *
 * 命中时返回**原因**（可直接用作 `Document.error`），未命中返回 `null`。
 * 返回原因而不是布尔值，是因为调用方要把它写进文档 —— 「为什么这篇没有正文」
 * 必须能在界面和报告里看到，否则用户只会看到一篇「内容很奇怪」的资料。
 *
 * 只在**已经拿到成段文本**之后调用：它的任务是「这段文本是不是正文」，
 * 不是「有没有拿到文本」—— 后者由 `Extraction.thin` 负责。
 */
export function boilerplateReason(text: string): string | null {
  const found = text.match(PLAY_MARK);
  if (found && found.length >= PLAY_MARK_MIN) {
    return `抽到的是视频推荐列表，不是正文（含 ${found.length} 处「N播放」计数标记）`;
  }

  for (const pattern of BILIBILI_CHROME) {
    if (pattern.test(text)) {
      return "抽到的是 B 站页面骨架（导航条 / 播放页工具条），不是正文";
    }
  }

  return null;
}
